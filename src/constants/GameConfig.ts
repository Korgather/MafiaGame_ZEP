/**
 * 밤 사망자 한 명을 감당하려면 시민 진영에 몇 명이 필요한가.
 *
 * 마피아 진영의 "인원"은 MAFIA_RATIO가 관리하지만 "밤에 시체가 몇 구
 * 나오는가"는 아무도 세지 않았다. 마피아 밀담에 낀 사람들은 상의해서 한
 * 명만 치므로 인원이 늘어도 시체는 하나지만, 밀담 밖에서 따로 죽이는
 * 직업(짐승인간)은 표적이 겹치지 않아 시체를 하나 더 만든다.
 *
 * 그래서 6명 판에 마피아+짐승인간이 뽑히면 첫 밤에 둘이 죽고 2 대 2가 되어,
 * 토론도 투표도 한 번 없이 아침에 게임이 끝났다.
 *
 * 값의 근거: 시민이 마피아 M명을 찾아내려면 투표를 M번 해야 하고, 한 라운드에
 * 밤 사망자 K명 + 처형 1명이 빠진다. (시민 수 - M) / (K + 1) >= M 이 성립해야
 * 하므로 밤 킬 하나당 시민 4명이 하한이다. 시민 6명(8인 판)이면 밤 킬은 하나뿐,
 * 시민 8명(10인 판)부터 둘을 감당한다.
 */
